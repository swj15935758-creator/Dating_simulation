# GPT가 사용자와 캐릭터의 대화를 분석하고
# XGBoost 모델에 전달할 특성을 추출하는 파일
# ==========================================


# GPT가 판단할 분석 특성 6개
ANALYSIS_FEATURE_RULES = """
[대화 분석 특성]

각 특성은 0.0부터 1.0 사이의 숫자로 평가한다.

1. preference_match (선호도 일치)
- 캐릭터가 좋아하는 행동이나 가치관과
  사용자의 발언 및 행동이 얼마나 일치하는지 평가한다.
- 캐릭터의 likes와 values를 참고한다.
- 일치하는 요소가 없거나 판단 근거가 부족하면 0.0으로 평가한다.
- 일치 정도가 높을수록 높은 값을 부여한다.

2. dislike_match (비선호도 일치)
- 사용자의 발언이나 행동이 캐릭터가 싫어하는 요소와
  얼마나 일치하는지 평가한다.
- 캐릭터의 dislikes를 참고한다.
- 싫어하는 행동이 나타나지 않았다면 0.0으로 평가한다.
- 싫어하는 행동이 명확하게 나타날수록 높은 값을 부여한다.
- 이 값은 부정적인 행동의 발생 정도를 의미한다.

3. empathy (공감)
- 사용자가 캐릭터의 감정이나 입장을 얼마나 이해하고
  공감했는지 평가한다.
- 단순히 긍정적인 말을 했다는 이유만으로
  높은 점수를 부여하지 않는다.
- 감정을 이해하고 적절하게 반응했는지 판단한다.

4. interest (관심도)
- 사용자가 캐릭터에게 얼마나 관심을 보였는지 평가한다.
- 적절한 질문, 상대방에 대한 관심,
  이전에 들은 내용에 대한 후속 질문 등을 참고한다.
- 질문의 개수만으로 판단하지 않는다.

5. sincerity (진정성)
- 사용자의 발언이 얼마나 진솔하고 성의 있는지 평가한다.
- 상대방을 존중하는 태도와 일관성을 참고한다.
- 무조건 긍정적인 말이나 칭찬을 한다고
  높은 점수를 부여하지 않는다.

6. context_match (맥락 일치)
- 사용자의 발언이 현재 대화 상황과
  이전 대화 내용에 얼마나 자연스럽게 연결되는지 평가한다.
- 현재 에피소드, 장소, 대화 흐름을 참고한다.
- 자유로운 주제 전환은 자연스럽다면 감점하지 않는다.
"""


# 분석할 때 지켜야 하는 공통 규칙
ANALYSIS_GUIDELINES = """
[분석 공통 규칙]

1. 실제 대화 내용을 근거로 판단한다.
2. 근거가 부족한 경우 무리하게 높은 값을 부여하지 않는다.
3. 긍정적인 대화라고 모든 특성을 높게 평가하지 않는다.
4. 부정적인 대화라고 모든 특성을 0으로 평가하지 않는다.
5. 각 특성은 서로 독립적으로 판단한다.
6. 캐릭터의 personality, likes, dislikes, values를 참고한다.
7. 캐릭터의 성격 유형에 따라 평가 기준을 일관되게 적용한다.
8. 사용자의 한 문장만 보지 말고 이전 대화 맥락도 참고한다.
9. 사용자의 말투나 표현 방식이 캐릭터와 다르다는 이유만으로 감점하지 않는다.
10. 분석은 사용자의 마지막 발언과 그에 대한 대화 맥락을 중심으로 수행한다.
"""


# Python에서 추가할 분석 특성 3개
PYTHON_MANAGED_FEATURES = [
    "repetition_count",
    "previous_affection",
    "previous_trust"
]


# GPT가 반환해야 하는 JSON 형식
ANALYSIS_OUTPUT_FORMAT = """
[출력 JSON 형식]

반드시 아래 구조를 따르는 JSON 객체 하나만 반환한다.

{
    "features": {
        "preference_match": 0.0,
        "dislike_match": 0.0,
        "empathy": 0.0,
        "interest": 0.0,
        "sincerity": 0.0,
        "context_match": 0.0
    },
    "reason": "분석 근거를 간결하게 설명"
}

[출력 제한]

- 모든 특성 값은 숫자형이어야 한다.
- 특성 값은 0.0 이상 1.0 이하여야 한다.
- reason은 한국어로 작성한다.
- JSON 이외의 설명이나 마크다운을 출력하지 않는다.
- JSON 키 이름을 변경하지 않는다.
- repetition_count, previous_affection, previous_trust는 출력하지 않는다.
- 호감도와 신뢰도 변화량을 직접 출력하지 않는다.
"""


# 전체 분석 프롬프트를 반환하는 함수
def get_analysis_prompt() -> str:

    # 분석 기준과 공통 규칙, JSON 출력 형식을 하나로 결합
    return "\n\n".join([
        ANALYSIS_FEATURE_RULES,
        ANALYSIS_GUIDELINES,
        ANALYSIS_OUTPUT_FORMAT
    ])
