# ==========================================
# 에피소드 정보 가져오기
# ==========================================

def get_episode(episode_number: int) -> dict:
    """
    에피소드 번호를 전달하면 해당 에피소드 정보를 반환한다.
    """

    episode = EPISODES.get(episode_number)

    # 존재하지 않는 에피소드 번호 확인
    if episode is None:
        raise ValueError(
            f"존재하지 않는 에피소드입니다: {episode_number}"
        )

    # 원본 설정이 직접 변경되지 않도록 복사해서 반환
    import copy

    return copy.deepcopy(episode)


# ==========================================
# 전체 에피소드 개수 반환
# ==========================================

def get_total_episodes() -> int:
    """
    전체 에피소드 개수를 반환한다.
    """

    return len(EPISODES)
